#!/usr/bin/env python
"""
Generate docs/RESULTS.md from the raw experiment JSONL.

Everything in the report is computed from the data, so regenerating after a new
run cannot leave stale numbers behind. Run after any job lands:

    python benchmarks/make_report.py
"""
from __future__ import annotations
import json, os, statistics as st, sys, collections, glob, datetime

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "docs", "RESULTS.md")

# Stream-CQSA is streamed by definition, so residency is not a label axis. The
# axes that vary are where the fp32 accumulator lives and whether the depth is
# pinned. `cqsa_host` (older runs) and `cqsa_accgpu` (current) are the SAME
# configuration and are labelled identically so the two generations line up.
LAB = {"sdpa":"SDPA","sdpa_flash":"SDPA (flash)","sdpa_mem":"SDPA (mem-eff.)",
       "flash":"FlashAttention-2",
       "cqsa_host":"Stream-CQSA acc=GPU","cqsa_accgpu":"Stream-CQSA acc=GPU",
       "cqsa_hostmin":"Stream-CQSA acc=CPU","cqsa_acccpu":"Stream-CQSA acc=CPU",
       "cqsa_auto":"Stream-CQSA (all on GPU)","cqsa_allgpu":"Stream-CQSA (all on GPU)"}

# Excluded from every table: everything device-resident. It needs the whole input
# set on the GPU *and* adds an accumulator, so it OOMs before the baselines it
# exists to rescue -- dominated, and not what the method is. Still in the raw
# JSONL for anyone reproducing the earlier sweeps.
EXCLUDE_PREFIX = ("cqsa_auto", "cqsa_allgpu")
def keep(m): return not m.startswith(EXCLUDE_PREFIX)
def lab(m):
    if "_itr" in m:
        b,i = m.rsplit("_itr",1); return f"{LAB.get(b,b)} itr={i}"
    return LAB.get(m,m)
def fN(n): return f"{n//1048576}M" if n>=1048576 else f"{n//1024}K"

def load(*dirs, corrected_only=False):
    seen={}
    for d in dirs:
        p=os.path.join(ROOT,"results","paper",d,"results.jsonl")
        if not os.path.exists(p): continue
        for line in open(p):
            if not line.strip(): continue
            r=json.loads(line)
            if corrected_only and "itr_requested" not in r.get("info",{}): continue
            seen[(r["method"],r["dtype"],r["direction"],r["N"],r.get("seed",0))]=r
    return list(seen.values())

def meta_of(d):
    p=os.path.join(ROOT,"results","paper",d,"meta.json")
    return json.load(open(p)) if os.path.exists(p) else {}

def dirs_matching(pat): return sorted(os.path.basename(x) for x in
    glob.glob(os.path.join(ROOT,"results","paper",pat)) if os.path.isdir(x))

L=[]
def w(s=""): L.append(s)

# ---------------------------------------------------------------- provenance
acc_dirs   = dirs_matching("accuracy_*")
sweep_dirs = dirs_matching("sweep_*") + dirs_matching("rewarm_*") + dirs_matching("gapfill_*")
acc  = load(*acc_dirs, corrected_only=True)
swp  = load(*sweep_dirs)
m0   = meta_of(sweep_dirs[0]) if sweep_dirs else {}

w("# Stream-CQSA: experimental results")
w()
w(f"*Generated by `benchmarks/make_report.py` on "
  f"{datetime.date.today().isoformat()} from the raw JSONL. Do not edit by hand — "
  f"rerun the generator so the numbers cannot drift from the data.*")
w()
w("| | |")
w("|---|---|")
w(f"| hardware | {m0.get('gpu','?')} ({m0.get('gpu_gib','?')} GiB) |")
w(f"| torch / flash-attn | {m0.get('torch','?')} / {m0.get('flash_attn','?')} |")
w(f"| shape | B={m0.get('B')} H={m0.get('H')} D={m0.get('D')}, causal |")
w(f"| CQS parameters | c=7, interest set (0,1,3) |")
w(f"| inputs | zero-mean Gaussian, unit variance (`--input-scale 1.0`) |")
w(f"| E1 rows | {len(acc)} from `{', '.join(acc_dirs)}` |")
w(f"| E2/E3 rows | {len(swp)} from `{', '.join(sweep_dirs)}` |")
w()
w("Baselines are exact-attention implementations only: Stream-CQSA preserves the "
  "attention function, so an approximate method would not answer the same "
  "question. **Every accuracy number below is measured against a float64 "
  "reference**, not against SDPA — SDPA is one of the methods under test, not "
  "the yardstick.")
w()

# ------------------------------------------------------------------------ E1
w("---")
w()
w("## E1 — Accuracy under precision")
w()
am = collections.Counter(r["acc_mode"] for r in acc)
Ns = sorted({r["N"] for r in acc})
w(f"Fixed N={Ns[0] if Ns else '?'}, {len({r['seed'] for r in acc})} seeds. "
  f"Reference: forward = exact float64 over sampled query rows "
  f"({[r['acc_rows'] for r in acc if r['acc_rows']][0] if any(r['acc_rows'] for r in acc) else '?'} rows); "
  f"backward = **dense** float64 (affordable at this N, so dQ/dK/dV are checked "
  f"against exact arithmetic rather than another approximation).")
w()
w(f"Reference modes actually used: `{dict(am)}`.")
w()
order=[m for m in ("sdpa","sdpa_flash","sdpa_mem","flash",
                   "cqsa_host_itr0","cqsa_host_itr1","cqsa_host_itr2",
                   "cqsa_accgpu_itr1","cqsa_accgpu_itrauto",
                   "cqsa_hostmin_itr1","cqsa_hostmin_itr2",
                   "cqsa_acccpu_itr1","cqsa_acccpu_itrauto")
       if any(r["method"]==m for r in acc) and keep(m)]
for d,dn in (("fwd","Forward"),("bwd","Backward")):
    w(f"### {dn} — relative error vs float64 (mean ± std over seeds)")
    w()
    w("| method | fp16 | bf16 | bf16/fp16 |")
    w("|---|--:|--:|--:|")
    for m in order:
        cells,mu={},{}
        for dt,dn2 in (("float16","fp16"),("bfloat16","bf16")):
            v=[r["acc_rel"] for r in acc if r["method"]==m and r["dtype"]==dt
               and r["direction"]==d and r["acc_rel"]==r["acc_rel"]]
            if v:
                mu[dn2]=st.mean(v)
                cells[dn2]=(f"{st.mean(v):.3e} ± {st.stdev(v):.0e}" if len(v)>1
                            else f"{st.mean(v):.3e}")
        if cells:
            rt=f"{mu['bf16']/mu['fp16']:.1f}×" if len(mu)==2 else "—"
            w(f"| {lab(m)} | {cells.get('fp16','—')} | {cells.get('bf16','—')} | {rt} |")
    w()
    if d=="bwd":
        w("Per-gradient breakdown (fp16, mean over seeds):")
        w()
        w("| method | dQ | dK | dV |")
        w("|---|--:|--:|--:|")
        for m in order:
            s2=[r for r in acc if r["method"]==m and r["dtype"]=="float16" and r["direction"]=="bwd"]
            if not s2: continue
            f=lambda k: st.mean([r[k] for r in s2 if r[k]==r[k]])
            w(f"| {lab(m)} | {f('acc_rel_dq'):.3e} | {f('acc_rel_dk'):.3e} | {f('acc_rel_dv'):.3e} |")
        w()

# --------------------------------------------------------------------- E2/E3
g={(r["dtype"],r["direction"],r["N"],r["method"]):r for r in swp}
sNs=sorted({r["N"] for r in swp})
methods=[m for m in ("sdpa","sdpa_mem","flash",
                     "cqsa_host_itr1","cqsa_host_itr2",
                     "cqsa_accgpu_itr1","cqsa_accgpu_itrauto",
                     "cqsa_hostmin_itr1","cqsa_hostmin_itr2","cqsa_hostmin_itr3",
                     "cqsa_acccpu_itr1","cqsa_acccpu_itrauto")
         if any(r["method"]==m for r in swp) and keep(m)]
w("---")
w()
w("## E2/E3 — Cost curve and OOM recovery")
w()
w("**The Stream-CQSA rows are all streamed** (host-resident Q/K/V) — that is what "
  "the method is. The all-on-GPU variant is excluded from every table: it needs "
  "the whole input set resident *and* adds an accumulator, so it OOMs before the "
  "baselines it exists to rescue. It remains in the raw JSONL.")
w()
w("The axis that does vary is **where the fp32 accumulator lives**:")
w()
w("| | accumulator | behaviour |")
w("|---|---|---|")
w("| `acc=GPU` | device | faster, but the accumulator is an O(N) *device* term "
  "that no depth of decomposition shrinks — so it OOMs first, and it OOMs **in "
  "the accumulation phase** rather than in the attention kernel |")
w("| `acc=CPU` | host | slower per subproblem, but removes that term entirely and "
  "so survives to the largest N — the safe default |")
w()
w(f"One ladder N ∈ {{{', '.join(fN(n) for n in sNs)}}}, both precisions, both "
  f"directions. E2 (overhead where the baseline runs) and E3 (recovery past the "
  f"wall) are the same sweep — the boundary is a point on the curve, not a "
  f"separate experiment.")
w()
w("### OOM boundary")
w()
w("| method | fwd: last OK | fwd: OOM at | bwd: last OK | bwd: OOM at |")
w("|---|--:|--:|--:|--:|")
for m in methods:
    cells=[]
    for d in ("fwd","bwd"):
        ok=[n for n in sNs if g.get(("float16",d,n,m),{}).get("status")=="ok"]
        oo=[n for n in sNs if g.get(("float16",d,n,m),{}).get("status")=="oom"]
        cells += [fN(max(ok)) if ok else "—", fN(min(oo)) if oo else "—"]
    w(f"| {lab(m)} | {cells[0]} | {cells[1]} | {cells[2]} | {cells[3]} |")
w()
w("*(fp16; bf16 boundaries are identical — memory does not depend on which "
  "16-bit type is used.)*")
w()
for d,dn in (("fwd","Forward"),("bwd","Backward")):
    w(f"### {dn} — wall clock (s) and peak GPU memory (GiB), fp16")
    w()
    big=[n for n in sNs if n>=1048576]
    w("| N | " + " | ".join(lab(m) for m in methods) + " |")
    w("|---" * (len(methods)+1) + "|")
    # A configuration with no row at this length, but measured out of memory at
    # a shorter one, is out of memory here too: peak memory rises monotonically
    # with N. Reporting that as "not run" implies a doubt that does not exist.
    oom_below = {}
    for m in methods:
        for n in sNs:
            r = g.get(("float16", d, n, m))
            if r and r["status"] == "oom":
                oom_below[m] = min(oom_below.get(m, 1 << 62), n)
    for n in big:
        tc,mc=[],[]
        for m in methods:
            r=g.get(("float16",d,n,m))
            if r and r["status"]=="ok":
                tc.append(f"{r['ms']/1000:.0f}"); mc.append(f"{r['mem_alloc_peak']/1024:.1f}")
            elif (r and r["status"]=="oom") or n > oom_below.get(m, 1 << 62):
                tc.append("**OOM**"); mc.append("—")
            else: tc.append("*not measured*"); mc.append("—")
        w(f"| **{fN(n)}** time | " + " | ".join(tc) + " |")
        w(f"| {fN(n)} peak | " + " | ".join(mc) + " |")
    w()
    w("Peak memory rises monotonically with `N`, so a configuration out of memory "
      "at one length is out of memory at every longer one.")
    w()

# ------------------------------------------------------------------- gaps
w("---")
w()
w("## Gaps and caveats")
w()
missing=[]
for dt in ("float16","bfloat16"):
    for d in ("fwd","bwd"):
        for n in [x for x in sNs if x>=8388608]:
            for m in methods:
                if (dt,d,n,m) not in g: missing.append((dt,d,n,m))
if missing:
    w(f"**{len(missing)} cells not yet measured** at N ≥ 8M. The main sweep ran "
      f"before OOM-retirement was made `itr`-aware, so an `itr=1` OOM suppressed "
      f"`itr=2` at the same N, and it predated the `cqsa_hostmin` "
      f"(host accumulator) configuration. Job `cqsa_gapfill` refills them; "
      f"rerun this generator afterwards.")
    w()
    seenk=sorted({(dt,d,fN(n),m.rsplit('_itr')[0]) for dt,d,n,m in missing})
    w("| dtype | dir | N | method family |")
    w("|---|---|---|---|")
    for dt,d,n,m in seenk[:12]:
        w(f"| {'fp16' if dt=='float16' else 'bf16'} | {d} | {n} | {LAB.get(m,m)} |")
    if len(seenk)>12: w(f"| … | | | {len(seenk)-12} more |")
    w()
w("**Memory metrics.** `peak` is `torch.cuda.max_memory_allocated()` (live "
  "tensors: reproducible, excludes allocator cache and CUDA context). The raw "
  "rows also carry `mem_reserved_peak` (what the allocator held from the driver "
  "— closer to real device pressure, and typically far larger), plus "
  "`mem_inputs_dev` / `mem_workspace` / `mem_host_bytes`. Quote `peak` when "
  "comparing methods and `reserved` when discussing how close a run sits to the "
  "card's limit; they answer different questions.")
w()
w("**Stage totals** (`stage_ms`) come from CUDA events. With several subproblems "
  "in flight an event span also covers time queued behind other streams, so the "
  "stages over-count wall clock and are a breakdown of where work is issued, not "
  "an additive partition of the measured runtime.")
w()
w("**Warm-up.** The main sweep used `--warmup 0`, correct where one call takes "
  "minutes but contaminating at small N, where the first call of each method "
  "carries CUDA context and kernel load (FlashAttention read 12,090 ms at "
  "N=8192 against a true 0.73 ms). The `rewarm` run re-measured N ≤ 256K with "
  "`--warmup 2 --reps 3` and supersedes those rows (later run wins on a "
  "duplicate key).")
w()
# This paragraph lives here rather than in the file it describes: RESULTS.md is
# generated, and an earlier version of this text was hand-edited into it and then
# silently overwritten on the next regeneration.
w("**Figures** are generated from the same data by "
  "`benchmarks/make_figures.py` into `docs/figures/`. "
  "[`notebooks/paper_figures.ipynb`](../notebooks/paper_figures.ipynb) rebuilds "
  "them with the selection rules written out cell by cell -- which rows are "
  "dropped and why -- and ends by re-deriving the tables above from whatever it "
  "just plotted, so a figure that drifts from a table fails the notebook.")
w()
w("Memory is plotted in GiB against the 79.3 GiB device limit on linear axes, "
  "because it is linear in `N` (measured ratio 2.00 across a doubling); time is "
  "plotted log-log, because it is quadratic (4.0). Each panel uses the scale on "
  "which its own growth is a straight line, so neither implies a rate the data "
  "does not have. The stage-breakdown figure plots each stage's *share* of the "
  "work issued at a given length rather than raw milliseconds, and excludes "
  "time spent queued behind another stream: that runs concurrently with the "
  "stage it would be charged to, so counting it in a proportion double-counts "
  "the concurrency instead of dividing the work.")

open(OUT,"w").write("\n".join(L)+"\n")
print(f"wrote {OUT}  ({len(L)} lines)")
